export type EduFact = { label: string; value: string };
export type EduGroupItem = {
  name: string;
  meta?: string;
  place?: string;
  /** 하위 부서별 특징 — 김창진 원고 "우리 부서의 특징" (2026-10-09) */
  features?: string[];
};
/** 바로가기 — `href`가 없으면 "준비 중"(비활성)으로 그린다. `/`로 시작하면 사이트 안 링크 */
export type EduLink = { label: string; href?: string };

export type EduDept = {
  /** 앵커 id — `lib/nav.ts`의 `/education#<id>`와 반드시 일치 */
  id: string;
  /** 시안의 섹션 번호 (01~06) */
  no: string;
  /** 번호 옆 영문 */
  en: string;
  title: string;
  lead: string;
  /** 제목 오른쪽 바로가기 (네이버 카페 등) */
  links?: EduLink[];
  /** 소개 카드 — 시안의 연한 블루 박스 */
  intro: { title: string; body: string; photoSlots?: number };
  /** 부서 카드 그룹 (주일학교 미취학부/초등부 등) */
  groups?: { label: string; items: EduGroupItem[] }[];
  /** 라벨-값 정보 (개강·수업시간·학기 등) */
  facts?: { title?: string; items: EduFact[] };
  /** 목록형 특징·혜택 */
  bullets?: { title: string; items: string[] };
  /** 소개 카드 위 성경 구절 (새소식반 — 오태희 원고) */
  verses?: { text: string; ref: string }[];
  /** 부서 공통 프로그램 칩 (주일학교 공통 — 김창진 원고) */
  common?: { title: string; items: string[] };
  /** 주요 행사 — 시안의 번호 카드 */
  events?: string[];
  faq?: { question: string; answer: string }[];
  /** 섹션 맨 아래 각주 */
  notes?: string[];
};

